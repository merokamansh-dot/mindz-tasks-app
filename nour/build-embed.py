#!/usr/bin/env python3
"""Builds nour/embed.js: NOUR (nour.js + scoped nour.css + portrait) mountable inside the Z Cloud home page.
Run from the repo root: python3 nour/build-embed.py"""
import re, base64, json
css = open('nour/nour.css', encoding='utf-8').read()
js = open('nour/nour.js', encoding='utf-8').read()
portrait = 'data:image/jpeg;base64,' + base64.b64encode(open('nour/nour-portrait.jpg', 'rb').read()).decode()
P = '#nour-embed'

def scope_sel(sel):
    out = []
    for s in sel.split(','):
        s = s.strip()
        if not s: continue
        if s == ':root' or s in ('html', 'body'): out.append(P)
        elif s == '*': out.append(P + ' *')
        else: out.append(P + ' ' + s)
    return ','.join(out)

def scope(css):
    res, i, n = [], 0, len(css)
    while i < n:
        m = re.compile(r'\s*([^{}]+)\{').match(css, i)
        if not m: break
        sel = m.group(1).strip(); j = m.end()
        if sel.startswith('@keyframes'):
            d = 1; k = j
            while d and k < n:
                d += (css[k] == '{') - (css[k] == '}'); k += 1
            res.append(sel + '{' + css[j:k]); i = k; continue
        if sel.startswith('@media'):
            d = 1; k = j
            while d and k < n:
                d += (css[k] == '{') - (css[k] == '}'); k += 1
            res.append(sel + '{' + scope(css[j:k - 1]) + '}'); i = k; continue
        k = css.index('}', j)
        res.append(scope_sel(sel) + '{' + css[j:k] + '}'); i = k + 1
    return ''.join(res)

scoped = scope(css)
scoped += (P + '{position:relative;border-radius:14px;overflow:hidden;font-size:15px;line-height:1.45;text-align:start}'
           + P + ' nav{position:static;top:auto}' + P + ' main{max-width:none;padding:10px 4px}'
           + P + ' .chat{height:min(680px,78vh);min-height:360px}' + P + ' button{margin:0}')

wrapper = r'''/* NOUR embed: lets NOUR run inside the Z Cloud home page with the signed-in session (generated by nour/build-embed.py; do not edit by hand) */
(function () {
  'use strict'
  if (window.__nourOpen) return
  var C = window.__MINDZ_CONFIG || {}
  var CSS = __CSS__, PORTRAIT = __PORTRAIT__
  window.__nourPortrait = PORTRAIT
  var KEY = C.url ? 'sb-' + C.url.replace(/^https?:\/\//, '').split('.')[0] + '-auth-token' : ''
  function tok() { try { var r = JSON.parse(localStorage.getItem(KEY) || 'null'); return r && r.access_token ? r : null } catch (e) { return null } }
  var cache = { t: null, c: null }
  // Uses the session Z Cloud already holds; never refreshes or rewrites it (so it cannot log anyone out).
  function cl() {
    var t = tok(); if (!t) throw new Error('not signed in')
    if (cache.t !== t.access_token) {
      cache.c = window.supabase.createClient(C.url, C.anonKey, { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false }, global: { headers: { Authorization: 'Bearer ' + t.access_token } } })
      cache.t = t.access_token
    }
    return cache.c
  }
  var facade = {
    from: function () { var c = cl(); return c.from.apply(c, arguments) },
    rpc: function () { var c = cl(); return c.rpc.apply(c, arguments) },
    storage: { from: function () { var c = cl(); return c.storage.from.apply(c.storage, arguments) } },
    auth: { getSession: function () { var t = tok(); return Promise.resolve({ data: { session: t ? { access_token: t.access_token, user: t.user } : null } }) } },
    functions: { invoke: function (name, o) {
      var t = tok(); if (!t) return Promise.resolve({ data: null, error: { message: 'not signed in' } })
      return fetch(C.url + '/functions/v1/' + name, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + t.access_token, apikey: C.anonKey }, body: JSON.stringify((o && o.body) || {}) })
        .then(function (r) { return r.json().catch(function () { return {} }).then(function (j) { return r.ok ? { data: j, error: null } : { data: j, error: { message: (j && j.error) || ('http ' + r.status) } } }) })
        .catch(function (e) { return { data: null, error: { message: String(e && e.message || e) } } })
    } }
  }
  function run(__NE) {
__NOURJS__
  }
  window.__nourOpen = function (root, mode) {
    if (!document.getElementById('nour-embed-css')) { var st = document.createElement('style'); st.id = 'nour-embed-css'; st.textContent = CSS; document.head.appendChild(st) }
    root.innerHTML = '<div class="boot">NOUR…</div>'
    var ne = { root: root, sb: facade, portrait: PORTRAIT, mode: mode || 'talk', stop: null }
    try { run(ne) } catch (e) { root.textContent = 'NOUR could not start: ' + (e && e.message || e) }
    return ne
  }
})()
'''
out = wrapper.replace('__CSS__', json.dumps(scoped)).replace('__PORTRAIT__', json.dumps(portrait)).replace('__NOURJS__', js)
open('nour/embed.js', 'w', encoding='utf-8').write(out)
print('embed.js', len(out))
